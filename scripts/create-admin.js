/**
 * RAMBOOW CLIENT MANAGEMENT — PRODUCTION ADMIN ONBOARDING SCRIPT
 * Creates the initial company administrator account in the production database.
 * Does NOT seed demo leads or dummy team members.
 *
 * Usage:
 *   node scripts/create-admin.js
 *
 * Optional Environment Variables:
 *   ADMIN_NAME="Rajesh Verma"
 *   ADMIN_EMAIL="admin@ramboow.com"
 *   ADMIN_PASSWORD="YourSecurePassword123"
 */

const { PrismaClient } = require("@prisma/client");
const bcrypt = require("bcryptjs");
const crypto = require("crypto");
const readline = require("readline");

const prisma = new PrismaClient();

function prompt(query) {
  const rl = readline.createInterface({
    input: process.stdin,
    output: process.stdout,
  });
  return new Promise((resolve) =>
    rl.question(query, (ans) => {
      rl.close();
      resolve(ans.trim());
    })
  );
}

function generateSecurePassword(length = 16) {
  const chars =
    "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789!@#$%^&*()_+";
  let pwd = "";
  for (let i = 0; i < length; i++) {
    const idx = crypto.randomInt(0, chars.length);
    pwd += chars[idx];
  }
  return pwd;
}

async function main() {
  console.log("==========================================================");
  console.log("   RAMBOOW CLIENT MANAGEMENT — CREATE PRODUCTION ADMIN   ");
  console.log("==========================================================\n");

  let name = process.env.ADMIN_NAME;
  let email = process.env.ADMIN_EMAIL;
  let password = process.env.ADMIN_PASSWORD;

  if (!name) {
    name = (await prompt("Enter Administrator Name (e.g. Rajesh Verma): ")) || "Ramboow Administrator";
  }

  if (!email) {
    email = await prompt("Enter Administrator Email: ");
  }

  if (!email || !email.includes("@")) {
    console.error("❌ Error: A valid email address is required.");
    process.exit(1);
  }

  email = email.toLowerCase().trim();

  let isAutoGenerated = false;
  if (!password) {
    const inputPass = await prompt(
      "Enter Administrator Password (leave blank to auto-generate secure 16-char password): "
    );
    if (inputPass) {
      password = inputPass;
    } else {
      password = generateSecurePassword(16);
      isAutoGenerated = true;
    }
  }

  if (password.length < 8) {
    console.error("❌ Error: Password must be at least 8 characters long.");
    process.exit(1);
  }

  console.log(`\nCreating administrator account for: ${name} <${email}>...`);

  // Hash password with 12 salt rounds
  const passwordHash = await bcrypt.hash(password, 12);

  const existingUser = await prisma.user.findUnique({ where: { email } });

  let adminUser;
  if (existingUser) {
    adminUser = await prisma.user.update({
      where: { email },
      data: {
        name,
        passwordHash,
        role: "ADMIN",
        active: true,
      },
    });
    console.log("✓ Existing user updated to Administrator with new password.");
  } else {
    adminUser = await prisma.user.create({
      data: {
        name,
        email,
        passwordHash,
        role: "ADMIN",
        active: true,
      },
    });
    console.log("✓ New Administrator account created successfully!");
  }

  // Create default service categories if not already present
  const defaultServices = [
    "Web Development",
    "Mobile App Development",
    "Cloud Solutions",
    "UI/UX Design",
    "Enterprise Software",
    "IT Consulting",
  ];

  for (const s of defaultServices) {
    try {
      await prisma.service.upsert({
        where: { name: s },
        update: {},
        create: { name: s },
      });
    } catch {}
  }
  console.log("✓ Service categories verified.");

  // Log to AuditLog
  await prisma.auditLog.create({
    data: {
      userId: adminUser.id,
      action: "ADMIN_INITIALIZED",
      details: `Administrator account initialized for ${name} (${email}).`,
    },
  });

  console.log("\n==========================================================");
  console.log("   ADMINISTRATOR ACCOUNT READY FOR PRODUCTION USE        ");
  console.log("==========================================================");
  console.log(` Name:     ${adminUser.name}`);
  console.log(` Email:    ${adminUser.email}`);
  console.log(` Role:     ADMIN`);
  if (isAutoGenerated) {
    console.log(` Generated Password: ${password}`);
    console.log(" ⚠️  Please store this password in a secure password manager immediately!");
  } else {
    console.log(" Password: [Securely stored hash in database]");
  }
  console.log("==========================================================\n");

  await prisma.$disconnect();
}

main().catch(async (e) => {
  console.error("Fatal error:", e);
  await prisma.$disconnect();
  process.exit(1);
});

